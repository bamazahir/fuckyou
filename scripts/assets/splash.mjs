// Renders the iOS launch screens (apple-touch-startup-image) and the social preview image from the app
// icon, in the Lamplight night colors. Writes PNGs to public/ and the <link> tags into index.html.
// Usage: node scripts/assets/splash.mjs   (uses Playwright's Chromium)
import { chromium } from '@playwright/test'
import { mkdir, readFile, writeFile } from 'node:fs/promises'

const root = new URL('../../', import.meta.url)
const svg = (await readFile(new URL('public/icons/icon.svg', root), 'utf8')).replace(
  '<svg ',
  '<svg width="100%" height="100%" ',
)
const font = async (p) => (await readFile(new URL(`node_modules/${p}`, root))).toString('base64')
const display = await font(
  '@fontsource-variable/bricolage-grotesque/files/bricolage-grotesque-latin-wght-normal.woff2',
)
const body = await font(
  '@fontsource/atkinson-hyperlegible/files/atkinson-hyperlegible-latin-400-normal.woff2',
)

const BG = '#2F3A5C'
const INK = '#F6EFE4'
const ACCENT = '#FFC86B'
const fonts = `
  @font-face { font-family: Display; src: url(data:font/woff2;base64,${display}) format('woff2'); font-weight: 200 800; }
  @font-face { font-family: Body; src: url(data:font/woff2;base64,${body}) format('woff2'); }
  body { margin: 0; background: ${BG}; color: ${INK}; height: 100vh; overflow: hidden; }`

// Portrait only (the manifest locks orientation). [CSS width, CSS height, pixel ratio]
const devices = [
  [430, 932, 3], // iPhone 14/15/16 Pro Max, 15/16 Plus
  [393, 852, 3], // iPhone 14/15/16 Pro, 15/16
  [428, 926, 3], // iPhone 12/13 Pro Max, 14 Plus
  [390, 844, 3], // iPhone 12/13/14
  [375, 812, 3], // iPhone X/XS/11 Pro, 12/13 mini
  [414, 896, 3], // iPhone XS Max, 11 Pro Max
  [414, 896, 2], // iPhone XR, 11
  [375, 667, 2], // iPhone SE (2nd/3rd), 8
  [820, 1180, 2], // iPad Air
  [834, 1194, 2], // iPad Pro 11"
  [1024, 1366, 2], // iPad Pro 12.9"
  [810, 1080, 2], // iPad 10.2"
]

const browser = await chromium.launch()
const page = await browser.newPage()
await mkdir(new URL('public/splash/', root), { recursive: true })
const links = []
for (const [w, h, dpr] of devices) {
  const name = `splash-${w * dpr}x${h * dpr}.png`
  await page.setViewportSize({ width: w * dpr, height: h * dpr })
  const icon = Math.round(Math.min(w, h) * dpr * 0.32)
  await page.setContent(`<style>${fonts}</style>
    <body style="display:flex;flex-direction:column;align-items:center;justify-content:center;gap:${icon * 0.18}px">
      <div style="width:${icon}px;height:${icon}px;border-radius:${icon * 0.22}px;overflow:hidden">${svg}</div>
      <div style="font:700 ${icon * 0.26}px Display">Studyroom</div>
    </body>`)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: new URL(`public/splash/${name}`, root).pathname })
  links.push(
    `    <link rel="apple-touch-startup-image" media="(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: portrait)" href="/splash/${name}" />`,
  )
  console.log('wrote', name)
}

// Social preview (Open Graph 1200x630): the icon, the name and the one-line pitch.
await page.setViewportSize({ width: 1200, height: 630 })
await page.setContent(`<style>${fonts}</style>
  <body style="display:flex;align-items:center;gap:64px;padding:0 96px;box-sizing:border-box">
    <div style="flex:none;width:300px;height:300px;border-radius:66px;overflow:hidden;border:6px solid #1A2038;box-shadow:14px 14px 0 #1A2038">${svg}</div>
    <div>
      <div style="font:800 112px/1 Display;letter-spacing:-2px">Studyroom</div>
      <div style="margin-top:28px;font:44px/1.25 Body;max-width:620px">A cozy study room you share with friends.</div>
      <div style="margin-top:36px;width:160px;height:12px;border-radius:6px;background:${ACCENT}"></div>
    </div>
  </body>`)
await page.evaluate(() => document.fonts.ready)
await page.screenshot({ path: new URL('public/og-image.png', root).pathname })
console.log('wrote og-image.png')
await browser.close()

const indexUrl = new URL('index.html', root)
const html = await readFile(indexUrl, 'utf8')
const block = `    <!-- splash:begin (generated by scripts/assets/splash.mjs) -->\n${links.join('\n')}\n    <!-- splash:end -->`
const next = /<!-- splash:begin[\s\S]*?<!-- splash:end -->/.test(html)
  ? html.replace(/ {4}<!-- splash:begin[\s\S]*?<!-- splash:end -->/, block)
  : html.replace('  </head>', `${block}\n  </head>`)
await writeFile(indexUrl, next)
console.log('updated index.html')
