create function private.valid_room_style(s jsonb) returns boolean
language sql immutable set search_path = '' as $$
  select coalesce(
    jsonb_typeof(s) = 'object'
    and (select coalesce(bool_and(k in ('wall', 'floor')), true) from jsonb_object_keys(s) k)
    and (s -> 'wall' is null or coalesce(s ->> 'wall', '') in
          ('theme', 'cream', 'sage', 'sky', 'blush', 'lavender', 'mint', 'navy', 'terracotta'))
    and (s -> 'floor' is null or coalesce(s ->> 'floor', '') in
          ('theme', 'oak', 'birch', 'walnut', 'cherry', 'slate', 'chalk')),
    false)
$$;
revoke all on function private.valid_room_style(jsonb) from public, anon, authenticated;
alter table public.rooms add constraint rooms_style_check check (private.valid_room_style(style));

create function public.set_room_style(p_room_id uuid, p_wall text, p_floor text) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := private.active_uid();
  v_room public.rooms;
begin
  select * into v_room from public.rooms where id = p_room_id;
  if not found then
    raise exception 'room_not_found' using errcode = 'P0002';
  end if;
  if v_room.is_personal then
    if v_room.owner_id <> v_uid then
      raise exception 'not_allowed' using errcode = '42501';
    end if;
  else
    perform private.require_role(p_room_id, 'owner', 'mod');
  end if;
  if private.over_limit('style', 20, 600) then
    raise exception 'rate_limited' using errcode = '54000';
  end if;
  begin
    update public.rooms set style = jsonb_build_object('wall', coalesce(p_wall, 'theme'), 'floor', coalesce(p_floor, 'theme'))
     where id = p_room_id;
  exception when check_violation then
    raise exception 'invalid_style' using errcode = '22023';
  end;
  if not v_room.is_personal then
    perform private.broadcast(p_room_id, 'layout', '{}'::jsonb);
  end if;
end;
$$;
revoke all on function public.set_room_style(uuid, text, text) from public, anon;
grant execute on function public.set_room_style(uuid, text, text) to authenticated;

-- room_info and visit_room return the style too.
create or replace function public.room_info(p_room_id uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not private.am_member(p_room_id) then
    raise exception 'not_a_member' using errcode = '42501';
  end if;
  return (
    select jsonb_build_object(
      'sync_pomodoro', r.sync_pomodoro, 'sync_focus_s', r.sync_focus_s, 'sync_break_s', r.sync_break_s,
      'sync_epoch', r.sync_epoch, 'notify_active', m.notify_active, 'layout', r.layout, 'bank_coins', r.bank_coins,
      'station_id', r.station_id, 'style', r.style, 'listed', r.listed)
      from public.rooms r join public.room_members m on m.room_id = r.id and m.user_id = (select auth.uid())
     where r.id = p_room_id
  );
end;
$$;

create or replace function public.visit_room(p_user_id uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_uid uuid := private.active_uid();
begin
  if p_user_id <> v_uid and (
       not exists (select 1 from public.room_members a join public.room_members b on b.room_id = a.room_id
                    join public.rooms r on r.id = a.room_id
                   where a.user_id = v_uid and b.user_id = p_user_id and not a.banned and not b.banned and not r.is_personal)
       or exists (select 1 from public.blocks
                   where (blocker_id = v_uid and blocked_id = p_user_id) or (blocker_id = p_user_id and blocked_id = v_uid))
       or not exists (select 1 from public.profiles where id = p_user_id and consent_status in ('not_required', 'granted'))) then
    raise exception 'not_allowed' using errcode = '42501';
  end if;
  return (select jsonb_build_object('display_name', p.display_name, 'avatar', p.avatar, 'layout', r.layout, 'style', r.style)
            from public.profiles p join public.rooms r on r.owner_id = p.id and r.is_personal
           where p.id = p_user_id);
end;
$$;

-- ---------------------------------------------------------------------------
-- All-time stats for the Stats tab: your own completed sessions, in your timezone
-- ---------------------------------------------------------------------------
create function public.my_stats() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_uid uuid := private.active_uid();
  v_tz text;
begin
  select tz into v_tz from public.profiles where id = v_uid;
  if not exists (select 1 from pg_catalog.pg_timezone_names where name = v_tz) then
    v_tz := 'UTC';
  end if;
  return (
    with done as (
      select s.started_at at time zone v_tz as local, coalesce(s.focus_seconds, 0) as secs, s.kind, s.room_id,
             s.planned_seconds
        from public.sessions s
       where s.user_id = v_uid and s.status = 'completed'
    ), days as (
      select (local::date) as d, sum(secs)::int as s from done
       where local >= (now() at time zone v_tz)::date - 370
       group by 1
    ), months as (
      select to_char(date_trunc('month', local), 'YYYY-MM') as m, sum(secs)::int as s from done
       where local >= date_trunc('month', now() at time zone v_tz) - interval '11 months'
       group by 1
    ), rooms as (
      select case when r.is_personal then null else r.name end as name, r.is_personal, sum(d.secs)::int as s
        from done d join public.rooms r on r.id = d.room_id
       group by r.id, r.name, r.is_personal
       order by 3 desc
       limit 6
    )
    select jsonb_build_object(
      'tz', v_tz,
      'total_seconds', coalesce((select sum(secs) from done), 0),
      'sessions', (select count(*) from done),
      'pomodoros', (select count(*) from done where kind = 'pomodoro' and secs >= 1200),
      'longest_seconds', coalesce((select max(secs) from done), 0),
      'first_day', (select to_char(min(local), 'YYYY-MM-DD') from done),
      'days', coalesce((select jsonb_agg(jsonb_build_object('d', to_char(d, 'YYYY-MM-DD'), 's', s) order by d) from days), '[]'),
      'months', coalesce((select jsonb_agg(jsonb_build_object('m', m, 's', s) order by m) from months), '[]'),
      'hours', (select jsonb_agg(coalesce((select sum(secs) from done where extract(hour from local) = h), 0)::int order by h)
                  from generate_series(0, 23) h),
      'weekdays', (select jsonb_agg(coalesce((select sum(secs) from done where extract(isodow from local) = w), 0)::int order by w)
                     from generate_series(1, 7) w),
      'rooms', coalesce((select jsonb_agg(jsonb_build_object('name', name, 'personal', is_personal, 's', s)) from rooms), '[]')
    )
  );
end;
$$;
revoke all on function public.my_stats() from public, anon;
grant execute on function public.my_stats() to authenticated;

-- ---------------------------------------------------------------------------
-- Discover (decision 0014): owners may list a room; people of the same age band can find and join
-- it. A listed room shows only its name and counts (never members' names or faces) until you join.
-- ---------------------------------------------------------------------------
create index rooms_listed_idx on public.rooms (listed) where listed;

-- 13–15, 16–17 and adults never see each other's listed rooms.
create function private.age_band(p_bracket text) returns text
language sql immutable set search_path = '' as $$
  select case when p_bracket in ('13', '14', '15') then 'young' when p_bracket = '16-17' then 'older' else 'adult' end
$$;

-- A listed room is discoverable by you only if every member is in your age band and nobody there
-- has blocked you (or been blocked by you).
create function private.discoverable(p_room_id uuid, p_uid uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.rooms r
     where r.id = p_room_id and r.listed and not r.is_personal
       and not exists (select 1 from public.room_members m where m.room_id = r.id and m.user_id = p_uid)
       and not exists (
         select 1 from public.room_members m join public.profiles p on p.id = m.user_id
          where m.room_id = r.id and not m.banned
            and private.age_band(p.age_bracket) <> (select private.age_band(age_bracket) from public.profiles where id = p_uid))
       and not exists (
         select 1 from public.room_members m join public.blocks b
             on (b.blocker_id = m.user_id and b.blocked_id = p_uid) or (b.blocker_id = p_uid and b.blocked_id = m.user_id)
          where m.room_id = r.id)
       and (select count(*) from public.room_members m where m.room_id = r.id and not m.banned) < 50)
$$;
revoke all on function private.discoverable(uuid, uuid) from public, anon, authenticated;

create function public.set_room_listed(p_room_id uuid, p_listed boolean) returns void
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := private.require_role(p_room_id, 'owner');
begin
  if p_listed and exists (
       select 1 from public.room_members m join public.profiles p on p.id = m.user_id
        where m.room_id = p_room_id and not m.banned
          and private.age_band(p.age_bracket) <> (select private.age_band(age_bracket) from public.profiles where id = v_uid)) then
    raise exception 'mixed_ages' using errcode = '22023';
  end if;
  update public.rooms set listed = coalesce(p_listed, false) where id = p_room_id and not is_personal;
end;
$$;

create function public.discover_rooms() returns table (
  id uuid, name text, member_count int, studying_count int, sync_pomodoro boolean
)
language plpgsql stable security definer set search_path = '' as $$
declare v_uid uuid := private.active_uid();
begin
  return query
    select r.id, r.name,
           (select count(*)::int from public.room_members m where m.room_id = r.id and not m.banned),
           (select count(*)::int from public.sessions s where s.room_id = r.id and s.status = 'active'),
           r.sync_pomodoro
      from public.rooms r
     where r.listed and private.discoverable(r.id, v_uid)
     order by 4 desc, 3 desc, r.created_at desc
     limit 30;
end;
$$;

create function public.join_listed_room(p_room_id uuid) returns public.rooms
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := private.active_uid();
  v_code text;
begin
  if not private.discoverable(p_room_id, v_uid) then
    raise exception 'room_not_found' using errcode = 'P0002';
  end if;
  select invite_code into v_code from public.rooms where id = p_room_id;
  return public.join_room(v_code); -- same checks and limits as an invite link
end;
$$;

