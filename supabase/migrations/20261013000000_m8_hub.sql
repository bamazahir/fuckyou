-- ---------------------------------------------------------------------------
-- Moving rooms: you study in one room at a time, but can carry a running session to another of
-- your rooms. The whole session then counts in the new room (decision 0014).
-- ---------------------------------------------------------------------------
create function public.move_session(p_room_id uuid) returns public.sessions
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := private.active_uid();
  v_room public.rooms;
  s public.sessions;
  v_from uuid;
begin
  if private.over_limit('move', 20, 600) then
    raise exception 'rate_limited' using errcode = '54000';
  end if;
  if not private.can_study_in(p_room_id, v_uid) then
    raise exception 'room_not_allowed' using errcode = '42501';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text, 0));
  select * into s from public.sessions where user_id = v_uid and status = 'active' for update;
  if not found then
    raise exception 'no_active_session' using errcode = 'P0002';
  end if;
  if s.room_id = p_room_id then
    return s;
  end if;
  select * into v_room from public.rooms where id = p_room_id;
  -- A shared-pomodoro room runs its own clock: join its next focus instead of bringing yours.
  if v_room.sync_pomodoro and not v_room.is_personal then
    raise exception 'sync_room_move' using errcode = '22023';
  end if;
  v_from := s.room_id;
  update public.sessions set room_id = p_room_id, sitting_id = gen_random_uuid()
   where id = s.id
  returning * into s;
  perform private.broadcast(v_from, 'state', jsonb_build_object('user_id', v_uid));
  perform private.broadcast(p_room_id, 'state', jsonb_build_object('user_id', v_uid));
  return s;
end;
$$;
revoke all on function public.move_session(uuid) from public, anon;
grant execute on function public.move_session(uuid) to authenticated;
