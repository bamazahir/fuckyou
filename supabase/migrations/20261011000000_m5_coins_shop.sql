-- rooms.bank_coins follows its ledger (SPEC §8.1).
create function private.bank_follow_ledger() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.rooms set bank_coins = bank_coins + new.delta where id = new.room_id;
  return new;
end;
$$;
create trigger room_bank_ledger_follow after insert on public.room_bank_ledger
  for each row execute function private.bank_follow_ledger();

create function private.balance(p_uid uuid) returns int
language sql stable security definer set search_path = '' as $$
  select coalesce(sum(delta), 0)::int from public.coin_ledger where user_id = p_uid
$$;

-- Starter items: for new people and new shared rooms, and for everyone who exists already.
create function private.grant_starter_personal() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.inventory (user_id, item_id, qty)
  select new.id, s.item_id, s.qty from public.catalog_starter s where s.scope = 'personal'
  on conflict do nothing;
  return new;
end;
$$;
create trigger profiles_starter_inventory after insert on public.profiles
  for each row execute function private.grant_starter_personal();

create function private.grant_starter_shared() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if not new.is_personal then
    insert into public.room_inventory (room_id, item_id, qty)
    select new.id, s.item_id, s.qty from public.catalog_starter s where s.scope = 'shared'
    on conflict do nothing;
  end if;
  return new;
end;
$$;
create trigger rooms_starter_inventory after insert on public.rooms
  for each row execute function private.grant_starter_shared();

insert into public.inventory (user_id, item_id, qty)
select p.id, s.item_id, s.qty from public.profiles p cross join public.catalog_starter s where s.scope = 'personal'
on conflict do nothing;
