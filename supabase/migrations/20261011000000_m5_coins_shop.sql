on conflict do nothing;

-- ---------------------------------------------------------------------------
-- Earning (SPEC §6.5): 1 coin per focus minute + 5 for a full pomodoro of 20+ min, with a note;
-- at most 720 a day in the person's timezone. Shared rooms also fill their bank.
-- ---------------------------------------------------------------------------
create function private.session_coins(p_focus_s int, p_kind text, p_planned_s int)
returns table (minutes int, bonus int)
language sql immutable set search_path = '' as $$
  select greatest(coalesce(p_focus_s, 0), 0) / 60,
         case when p_kind = 'pomodoro' and coalesce(p_planned_s, 0) >= 1200
                   and coalesce(p_focus_s, 0) >= coalesce(p_planned_s, 0) then 5 else 0 end
$$;

create or replace function public.submit_note(p_session_id uuid, p_note text, p_public boolean default false) returns int
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := private.active_uid();
  v_note text := btrim(p_note);
  s public.sessions;
  v_tz text;
  v_today int;
  v_left int;
  v_min int;
  v_bonus int;
  v_paid int := 0;
begin
  if char_length(v_note) not between 3 and 140 then
    raise exception 'invalid_note' using errcode = '22023';
  end if;
  if coalesce(p_public, false) then
    perform private.require_clean(v_note); -- shown to the room, so filtered like every public text
  end if;
  update public.sessions
     set note = v_note, note_public = coalesce(p_public, false)
   where id = p_session_id and user_id = v_uid and status = 'completed' and note is null
     and ended_at >= now() - interval '24 hours'
  returning * into s;
  if not found then
    raise exception 'note_not_possible' using errcode = 'P0002';
  end if;
  insert into public.events (user_id, name) values (v_uid, 'note_submitted');

  if not s.coins_paid then
    select tz into v_tz from public.profiles where id = v_uid;
    if not exists (select 1 from pg_catalog.pg_timezone_names where name = v_tz) then
      v_tz := 'UTC';
    end if;
    -- Serialise per person so two notes at once can't both slip under the daily cap.
    perform pg_advisory_xact_lock(hashtextextended('coins:' || v_uid::text, 0));
    select coalesce(sum(delta), 0)::int into v_today from public.coin_ledger
     where user_id = v_uid and reason in ('session', 'bonus')
       and created_at >= (date_trunc('day', now() at time zone v_tz)) at time zone v_tz;
    v_left := greatest(720 - v_today, 0);
    select c.minutes, c.bonus into v_min, v_bonus from private.session_coins(s.focus_seconds, s.kind, s.planned_seconds) c;
    v_min := least(v_min, v_left);
    v_bonus := least(v_bonus, v_left - v_min);
    if v_min > 0 then
      insert into public.coin_ledger (user_id, delta, reason, ref) values (v_uid, v_min, 'session', s.id);
    end if;
    if v_bonus > 0 then
      insert into public.coin_ledger (user_id, delta, reason, ref) values (v_uid, v_bonus, 'bonus', s.id);
    end if;
    update public.sessions set coins_paid = true where id = s.id;
    v_paid := v_min + v_bonus;
  end if;
  return v_paid;
end;
$$;

-- Room bank auto-fill: half a coin per focus minute in shared rooms, at most 360 per member per room per
-- day (room timezone), on top of the member's own earnings. Voiding reverses both.
create function private.sessions_coin_effects() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_room public.rooms;
  v_today int;
  v_add int;
  v_back int;
begin
  if new.status = 'completed' and old.status = 'active' then
    select * into v_room from public.rooms where id = new.room_id;
    if not v_room.is_personal then
      select coalesce(sum(delta), 0)::int into v_today from public.room_bank_ledger
       where room_id = new.room_id and user_id = new.user_id and reason = 'study'
         and created_at >= (date_trunc('day', now() at time zone v_room.tz)) at time zone v_room.tz;
      v_add := least(coalesce(new.focus_seconds, 0) / 120, greatest(360 - v_today, 0));
      if v_add > 0 then
        insert into public.room_bank_ledger (room_id, user_id, delta, reason, ref)
        values (new.room_id, new.user_id, v_add, 'study', new.id);
      end if;
    end if;
  elsif new.status = 'voided' and old.status <> 'voided' then
    select coalesce(sum(delta), 0)::int into v_back from public.coin_ledger
     where ref = new.id and reason in ('session', 'bonus', 'void');
    if v_back > 0 then
      insert into public.coin_ledger (user_id, delta, reason, ref) values (new.user_id, -v_back, 'void', new.id);
    end if;
    select coalesce(sum(delta), 0)::int into v_back from public.room_bank_ledger
     where ref = new.id and reason in ('study', 'void');
    if v_back > 0 then
      insert into public.room_bank_ledger (room_id, user_id, delta, reason, ref)
      values (new.room_id, new.user_id, -v_back, 'void', new.id);
    end if;
  end if;
  return new;
end;
$$;
create trigger sessions_coin_effects after update of status on public.sessions
  for each row execute function private.sessions_coin_effects();

