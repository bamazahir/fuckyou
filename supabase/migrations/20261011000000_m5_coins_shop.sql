create table public.coin_ledger (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  delta int not null check (delta <> 0),
  reason text not null check (reason in ('session', 'bonus', 'purchase', 'donate', 'void', 'admin')),
  ref uuid,
  created_at timestamptz not null default now()
);
create index coin_ledger_user_idx on public.coin_ledger (user_id, created_at);
create index coin_ledger_ref_idx on public.coin_ledger (ref) where ref is not null;
alter table public.coin_ledger enable row level security;
revoke all on table public.coin_ledger from anon, authenticated;
grant select on table public.coin_ledger to authenticated;
create policy coin_ledger_own on public.coin_ledger for select to authenticated using (user_id = (select auth.uid()));

create table public.room_bank_ledger (
  id bigint generated always as identity primary key,
  room_id uuid not null references public.rooms (id) on delete cascade,
  user_id uuid references public.profiles (id) on delete set null,
  delta int not null check (delta <> 0),
  reason text not null check (reason in ('study', 'donate', 'purchase', 'void')),
  ref uuid,
  created_at timestamptz not null default now()
);
create index room_bank_ledger_room_idx on public.room_bank_ledger (room_id, created_at);
create index room_bank_ledger_ref_idx on public.room_bank_ledger (ref) where ref is not null;
alter table public.room_bank_ledger enable row level security;
revoke all on table public.room_bank_ledger from anon, authenticated;
grant select on table public.room_bank_ledger to authenticated;
create policy room_bank_ledger_members on public.room_bank_ledger for select to authenticated
  using ((select private.am_member(room_id)));

